using DevProxy.Abstractions.Models;
using DevProxy.Abstractions.Plugins;
using DevProxy.Abstractions.Proxy;
using DevProxy.Abstractions.Proxy.Http;
using DevProxy.Abstractions.Utils;
using DevProxy.Plugins.Models;
using DevProxy.Plugins.Utils;
using Microsoft.Extensions.Logging;
using System.Collections.Concurrent;
using System.Net;
using System.Net.Http.Json;
using System.Text.Json;

namespace DevProxy.Plugins.Guidance;

public sealed class GraphMissingPermissionsGuidancePlugin(
    HttpClient httpClient,
    ILogger<GraphMissingPermissionsGuidancePlugin> logger,
    ISet<UrlToWatch> urlsToWatch) : BasePlugin(logger, urlsToWatch)
{
    private static readonly HashSet<string> SharedDataResources = new(
        ["messages", "mailFolders", "events", "calendar", "calendars", "calendarView", "calendarGroups", "contacts", "contactFolders"],
        StringComparer.OrdinalIgnoreCase);
    private const string ConsumersTenantId = "9188040d-6c67-4c5b-b112-36a304b66dad";
    private static readonly TimeSpan PermissionsLookupTimeout = TimeSpan.FromSeconds(3);
    private static readonly HashSet<string> SelfOnlyDelegatedPermissions = new(["User.Read", "User.ReadWrite"], StringComparer.OrdinalIgnoreCase);

#pragma warning disable CA2213 // Disposable fields should be disposed - HttpClient is injected via DI
    private readonly HttpClient _httpClient = httpClient;
#pragma warning restore CA2213
    private readonly ConcurrentDictionary<string, GraphPermissionInfo[]> _permissionsCache = new(StringComparer.OrdinalIgnoreCase);
    private readonly ConcurrentDictionary<string, Lazy<Task<GraphPermissionInfo[]?>>> _pendingLookups = new(StringComparer.OrdinalIgnoreCase);

    public override string Name => nameof(GraphMissingPermissionsGuidancePlugin);

    public override async Task AfterResponseAsync(ProxyResponseArgs e, CancellationToken cancellationToken)
    {
        Logger.LogTrace("{Method} called", nameof(AfterResponseAsync));

        ArgumentNullException.ThrowIfNull(e);

        var loggingContext = new LoggingContext(e.ProxySession);
        var request = e.ProxySession.Request;
        var response = e.ProxySession.Response;

        if (!e.HasRequestUrlMatch(UrlsToWatch))
        {
            Logger.LogRequest("URL not matched", MessageType.Skipped, loggingContext);
            return;
        }
        if (string.Equals(request.Method, "OPTIONS", StringComparison.OrdinalIgnoreCase))
        {
            Logger.LogRequest("Skipping OPTIONS request", MessageType.Skipped, loggingContext);
            return;
        }
        if (!ProxyUtils.IsGraphRequest(request))
        {
            Logger.LogRequest("Not a Microsoft Graph request", MessageType.Skipped, loggingContext);
            return;
        }
        if (response is null)
        {
            Logger.LogRequest("No response", MessageType.Skipped, loggingContext);
            return;
        }
        if (e.ProxySession.RespondedByPlugin)
        {
            Logger.LogRequest("Skipping response generated by a plugin", MessageType.Skipped, loggingContext);
            return;
        }

        if (ProxyUtils.IsGraphBatchUrl(request.RequestUri))
        {
            if (response.StatusCode != HttpStatusCode.OK)
            {
                Logger.LogRequest("Skipping non-successful batch response", MessageType.Skipped, loggingContext);
                return;
            }

            var failedRequests = GetForbiddenRequestsFromBatch(request.BodyString, response.BodyString);
            if (failedRequests.Count == 0)
            {
                Logger.LogRequest("No forbidden requests in batch", MessageType.Skipped, loggingContext);
                return;
            }

            var (permissionsType, tokenPermissions, userIdentifiers, isPersonalAccount) = GetTokenInfo(request);
            var graphVersion = ProxyUtils.IsGraphBetaUrl(request.RequestUri) ? "beta" : "v1.0";
            // analyze in parallel to limit the delay before the response is sent to the client
            var guidance = await Task.WhenAll(failedRequests.Select(failedRequest =>
            {
                var relativeUrl = failedRequest.Url.StartsWith('/') ? failedRequest.Url : $"/{failedRequest.Url}";
                var absoluteUrl = $"https://{request.RequestUri.Host}/{graphVersion}{relativeUrl}";
                return AnalyzeForbiddenRequestAsync(
                    failedRequest.Method,
                    absoluteUrl,
                    $"Batch request {failedRequest.Id} ({failedRequest.Method} {failedRequest.Url})",
                    permissionsType,
                    tokenPermissions,
                    userIdentifiers,
                    isPersonalAccount,
                    cancellationToken);
            }));
            foreach (var (message, messageType) in guidance)
            {
                LogGuidance(message, messageType, loggingContext);
            }
        }
        else if (response.StatusCode == HttpStatusCode.Forbidden)
        {
            var (permissionsType, tokenPermissions, userIdentifiers, isPersonalAccount) = GetTokenInfo(request);
            var (message, messageType) = await AnalyzeForbiddenRequestAsync(
                request.Method,
                request.RequestUri.AbsoluteUri,
                "Request",
                permissionsType,
                tokenPermissions,
                userIdentifiers,
                isPersonalAccount,
                cancellationToken);
            LogGuidance(message, messageType, loggingContext);
        }
        else
        {
            Logger.LogRequest("Skipping non-403 response", MessageType.Skipped, loggingContext);
        }

        Logger.LogTrace("Left {Name}", nameof(AfterResponseAsync));
    }

    private static (GraphPermissionsType? Type, IEnumerable<string> Permissions, string[] UserIdentifiers, bool IsPersonalAccount) GetTokenInfo(IHttpRequest request)
    {
        var authorizationHeader = request.Headers.GetFirst("Authorization")?.Value;
        var (permissionsType, tokenPermissions) = GraphUtils.GetPermissionsFromAuthorizationHeader(authorizationHeader);
        if (permissionsType != GraphPermissionsType.Delegated)
        {
            return (permissionsType, tokenPermissions, [], false);
        }

        var (userIdentifiers, tenantId) = GraphUtils.GetUserInfoFromAuthorizationHeader(authorizationHeader);
        var isPersonalAccount = string.Equals(tenantId, ConsumersTenantId, StringComparison.OrdinalIgnoreCase);
        return (permissionsType, tokenPermissions, userIdentifiers, isPersonalAccount);
    }

    private void LogGuidance(string? message, MessageType messageType, LoggingContext loggingContext)
    {
        if (message is not null)
        {
            Logger.LogRequest(message, messageType, loggingContext);
        }
    }

    private async Task<(string? Message, MessageType Type)> AnalyzeForbiddenRequestAsync(
        string method,
        string absoluteUrl,
        string requestDescription,
        GraphPermissionsType? permissionsType,
        IEnumerable<string> tokenPermissions,
        string[] userIdentifiers,
        bool isPersonalAccount,
        CancellationToken cancellationToken)
    {
        if (permissionsType is null)
        {
            return ($"{requestDescription} failed with 403 Forbidden. Dev Proxy couldn't read permissions from the access token on the request so it can't tell if the request failed due to missing permissions. Make sure the request includes a valid bearer token (JWT) issued for Microsoft Graph.",
                MessageType.Warning);
        }

        string tokenizedUrl;
        try
        {
            tokenizedUrl = GraphUtils.GetTokenizedUrl(absoluteUrl);
        }
        catch (Exception ex)
        {
            Logger.LogDebug(ex, "Failed to tokenize URL {Url}", absoluteUrl);
            return ($"{requestDescription} failed with 403 Forbidden, but Dev Proxy couldn't analyze missing permissions for {method} {absoluteUrl} because it couldn't parse the URL. Check the Microsoft Graph API reference for the permissions required to call this API.",
                MessageType.Tip);
        }

        // personal Microsoft accounts support a different set of delegated permissions
        var scopeType = isPersonalAccount ? "DelegatedPersonal" : GraphUtils.GetScopeTypeString(permissionsType.Value);
        var requiredPermissions = await GetPermissionsAsync(method, tokenizedUrl, scopeType, cancellationToken);
        if (requiredPermissions is null || requiredPermissions.Length == 0)
        {
            return ($"{requestDescription} failed with 403 Forbidden. Dev Proxy couldn't determine which permissions are required for {method} {tokenizedUrl}. Check the Microsoft Graph API reference for the permissions required to call this API.",
                MessageType.Warning);
        }

        var mayTargetOtherUser = permissionsType == GraphPermissionsType.Delegated &&
            tokenizedUrl.StartsWith("/users/", StringComparison.OrdinalIgnoreCase) &&
            !IsSignedInUser(absoluteUrl, userIdentifiers);

        // delegated mail, calendar and contacts permissions only cover another
        // user's data if that user shared it with the signed-in user
        var otherUserDataNote = mayTargetOtherUser && IsSharedDataResource(tokenizedUrl)
            ? " If the request accesses another user's mailbox, calendar, or contacts, delegated permissions only work if that user shared the data with the signed-in user (or delegated access to it), and the app uses the corresponding .Shared permission, such as Mail.Read.Shared or Calendars.Read.Shared. Alternatively, use application permissions."
            : string.Empty;

        // delegated self-only permissions, like User.Read, are listed for
        // /users/{id} but only grant access to the signed-in user
        var selfOnlyNote = string.Empty;
        if (mayTargetOtherUser)
        {
            var selfOnlyPermissions = requiredPermissions
                .Where(p => SelfOnlyDelegatedPermissions.Contains(p.Value))
                .Select(p => p.Value)
                .ToArray();
            var otherUserPermissions = requiredPermissions
                .Where(p => !SelfOnlyDelegatedPermissions.Contains(p.Value))
                .ToArray();
            if (selfOnlyPermissions.Length > 0 && otherUserPermissions.Length > 0)
            {
                requiredPermissions = otherUserPermissions;
                selfOnlyNote = $" The {FormatList(selfOnlyPermissions)} permission(s) only allow access to the signed-in user. If you're calling the API for the signed-in user, use /me instead.";
            }
        }

        var tokenPermissionsSet = new HashSet<string>(tokenPermissions, StringComparer.OrdinalIgnoreCase);
        var grantingPermissions = requiredPermissions
            .Select(p => p.Value)
            .Where(tokenPermissionsSet.Contains)
            .ToArray();

        if (grantingPermissions.Length > 0)
        {
            return ($"{requestDescription} failed with 403 Forbidden even though the access token has the {FormatList(grantingPermissions)} {GetPermissionsTypeString(permissionsType.Value)} permission(s) which allow calling {method} {tokenizedUrl}. The request likely failed for another reason, for example: the {(permissionsType == GraphPermissionsType.Delegated ? "signed-in user" : "app")} doesn't have access to the resource, a required license or administrative role is missing, or the resource is restricted by a policy. Check the error details in the response for more information." + otherUserDataNote,
                MessageType.Warning);
        }

        var leastPrivileged = requiredPermissions
            .Where(p => p.IsLeastPrivilege)
            .Select(p => p.Value)
            .ToArray();
        var otherPermissions = requiredPermissions
            .Select(p => p.Value)
            .Except(leastPrivileged, StringComparer.OrdinalIgnoreCase)
            .ToArray();

        var tokenPermissionsString = tokenPermissionsSet.Count > 0
            ? FormatList(tokenPermissionsSet.Order(StringComparer.OrdinalIgnoreCase))
            : "none";

        var message = $"{requestDescription} failed with 403 Forbidden because the access token doesn't have the permissions required to call {method} {tokenizedUrl}. " +
            $"{CapitalizeFirst(GetPermissionsTypeString(permissionsType.Value))} permissions on the token: {tokenPermissionsString}. " +
            (leastPrivileged.Length > 0
                ? $"Add the least privileged permission: {FormatList(leastPrivileged)}." +
                    (otherPermissions.Length > 0 ? $" Alternatively, use one of the following higher-privileged permissions: {FormatList(otherPermissions)}." : string.Empty)
                : $"Add any of the following permissions: {FormatList(otherPermissions)}.") +
            selfOnlyNote +
            otherUserDataNote +
            " " + GetInstructions(permissionsType.Value);

        return (message, MessageType.Failed);
    }

    private async Task<GraphPermissionInfo[]?> GetPermissionsAsync(
        string method,
        string tokenizedUrl,
        string scopeType,
        CancellationToken cancellationToken)
    {
        var cacheKey = $"{scopeType}|{method}|{tokenizedUrl}";
        if (_permissionsCache.TryGetValue(cacheKey, out var cachedPermissions))
        {
            Logger.LogDebug("Using cached permissions for {CacheKey}", cacheKey);
            return cachedPermissions;
        }

        // coalesce concurrent lookups for the same key; the shared lookup isn't
        // tied to any caller's cancellation token so that one cancelled caller
        // doesn't fail the others
        Lazy<Task<GraphPermissionInfo[]?>>? newLookup = null;
        newLookup = new(LookupAsync);
        var lookup = _pendingLookups.GetOrAdd(cacheKey, newLookup);
        return await lookup.Value.WaitAsync(cancellationToken);

        async Task<GraphPermissionInfo[]?> LookupAsync()
        {
            try
            {
                return await FetchPermissionsAsync(cacheKey, method, tokenizedUrl, scopeType);
            }
            finally
            {
                // successful results are in the cache; failed lookups are
                // removed so that they can be retried
                _ = _pendingLookups.TryRemove(new KeyValuePair<string, Lazy<Task<GraphPermissionInfo[]?>>>(cacheKey, newLookup!));
            }
        }
    }

    private async Task<GraphPermissionInfo[]?> FetchPermissionsAsync(
        string cacheKey,
        string method,
        string tokenizedUrl,
        string scopeType)
    {
        var url = $"https://graph-devx-api.microsoft.com/permissions?scopeType={scopeType}&requesturl={Uri.EscapeDataString(tokenizedUrl)}&method={Uri.EscapeDataString(method.ToUpperInvariant())}";

        try
        {
            using var cts = new CancellationTokenSource(PermissionsLookupTimeout);

            Logger.LogDebug("Retrieving permissions from {Url}", url);
            using var response = await _httpClient.GetAsync(new Uri(url), cts.Token);
            if (response.StatusCode == HttpStatusCode.NotFound)
            {
                Logger.LogDebug("No permissions found for {Method} {Url}", method, tokenizedUrl);
                _permissionsCache[cacheKey] = [];
                return [];
            }
            if (!response.IsSuccessStatusCode)
            {
                Logger.LogDebug("Failed to retrieve permissions for {Method} {Url}: {StatusCode}", method, tokenizedUrl, response.StatusCode);
                return null;
            }

            var permissions = (await response.Content.ReadFromJsonAsync<GraphPermissionInfo[]>(ProxyUtils.JsonSerializerOptions, cts.Token) ?? [])
                .Where(p => !p.IsHidden && !string.IsNullOrEmpty(p.Value))
                .ToArray();
            _permissionsCache[cacheKey] = permissions;
            return permissions;
        }
        catch (Exception ex) when (ex is HttpRequestException or JsonException or OperationCanceledException)
        {
            Logger.LogDebug(ex, "Failed to retrieve permissions for {Method} {Url}", method, tokenizedUrl);
            return null;
        }
    }

    private List<GraphBatchRequestPayloadRequest> GetForbiddenRequestsFromBatch(string requestBody, string responseBody)
    {
        if (string.IsNullOrEmpty(requestBody) || string.IsNullOrEmpty(responseBody))
        {
            return [];
        }

        try
        {
            var batchRequest = JsonSerializer.Deserialize<GraphBatchRequestPayload>(requestBody, ProxyUtils.JsonSerializerOptions);
            var batchResponse = JsonSerializer.Deserialize<GraphBatchResponsePayload>(responseBody, ProxyUtils.JsonSerializerOptions);
            if (batchRequest is null || batchResponse is null)
            {
                return [];
            }

            var forbiddenIds = batchResponse.Responses
                .Where(r => r.Status == (int)HttpStatusCode.Forbidden)
                .Select(r => r.Id)
                .ToHashSet(StringComparer.Ordinal);

            return [.. batchRequest.Requests.Where(r => forbiddenIds.Contains(r.Id) && !string.IsNullOrEmpty(r.Url))];
        }
        catch (JsonException ex)
        {
            Logger.LogDebug(ex, "Failed to parse batch request or response");
            return [];
        }
    }

    private static bool IsSharedDataResource(string tokenizedUrl)
    {
        // segments: "", "users", "{users-id}", "{resource}", ...
        var segments = tokenizedUrl.Split('/');
        return segments.Length > 3 && SharedDataResources.Contains(segments[3]);
    }

    private static bool IsSignedInUser(string absoluteUrl, string[] userIdentifiers)
    {
        // segments: "/", "{version}/", "users/", "{id}/", ...
        var segments = new Uri(absoluteUrl).Segments;
        if (userIdentifiers.Length == 0 || segments.Length < 4)
        {
            return false;
        }

        var userId = Uri.UnescapeDataString(segments[3].TrimEnd('/'));
        return userIdentifiers.Contains(userId, StringComparer.OrdinalIgnoreCase);
    }

    private static string GetInstructions(GraphPermissionsType permissionsType) => permissionsType switch
    {
        GraphPermissionsType.Delegated => "To fix it, add the permission to the delegated permissions of your app registration in Microsoft Entra ID, include it in the scopes your app requests when acquiring the access token, and make sure the user (or an administrator, for permissions that require admin consent) consents to it.",
        GraphPermissionsType.Application => "To fix it, add the permission to the application permissions of your app registration in Microsoft Entra ID, grant admin consent for it, and acquire a new access token.",
        _ => string.Empty
    };

    private static string GetPermissionsTypeString(GraphPermissionsType permissionsType) => permissionsType switch
    {
        GraphPermissionsType.Delegated => "delegated",
        GraphPermissionsType.Application => "application",
        _ => permissionsType.ToString()
    };

    private static string CapitalizeFirst(string value) =>
        string.IsNullOrEmpty(value) ? value : char.ToUpperInvariant(value[0]) + value[1..];

    private static string FormatList(IEnumerable<string> values) => string.Join(", ", values);
}
